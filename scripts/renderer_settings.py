#!/usr/bin/env python3
"""The renderer settings this release's engine reads, for Settings › Advanced › Custom renderer
settings (REC-85), whose typo check flags any other name.

DXMT reads its options by exact name (Config::getOption<T>("name")) and silently ignores any it
doesn't read. This lists every name in DXMT at its pinned commit with the accepted patches applied
(the patches and their order are build_portable_dxmt.py's), with the kind of value each takes, and
writes app/Sources/RendererEngineSettings.swift. --check fails when that file is stale, as after a
new DXMT patch (tests/test_renderer_settings.py).

    python3 scripts/renderer_settings.py [--source <DXMT checkout>] [--check]
"""
import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT/'app/Sources/RendererEngineSettings.swift'
SOURCE = ROOT/'runtime/source/dxmt-ow2'
# DXMT's own value parsers (src/util/config/config.cpp): bool takes true or false in any case, the
# integers digits with an optional minus, float digits with an optional fraction; strings anything.
KINDS = {'bool': 'bool', 'int': 'int', 'int32_t': 'int', 'uint32_t': 'int', 'float': 'float',
         'std::string': 'text', 'Tristate': 'tristate'}
OPTION = re.compile(r'getOption<\s*([A-Za-z_:0-9 ]+?)\s*>\s*\(\s*"([A-Za-z0-9._]+)"')


def build():
    text = (ROOT/'scripts/build_portable_dxmt.py').read_text()
    base = re.search(r"^BASE='([0-9a-f]{40})'", text, re.M).group(1)
    # Every patch prepare_source applies, in its order.
    body = text.split('def prepare_source', 1)[1].split('\ndef ', 1)[0]
    patches = list(dict.fromkeys(re.findall(r"ROOT/'patches/(dxmt-[^']+\.patch)'", body)))
    return base, patches


def settings(source=SOURCE):
    """{name: kind} for DXMT at the build's commit with the build's patches."""
    base, patches = build()
    with tempfile.TemporaryDirectory(prefix='renderer-settings-') as work:
        tree = subprocess.run(['git', '-C', str(source), 'archive', base, 'src'], capture_output=True, check=True).stdout
        subprocess.run(['tar', '-x', '-C', work], input=tree, check=True)
        for patch in patches:
            subprocess.run(['git', 'apply', '--include=src/*', '--whitespace=nowarn', str(ROOT/'patches'/patch)],
                           cwd=work, check=True, capture_output=True)
        found = {}
        for path in sorted(Path(work, 'src').rglob('*')):
            if path.suffix in ('.c', '.cc', '.cpp', '.h', '.hpp', '.m', '.mm') and path.is_file():
                for kind, name in OPTION.findall(path.read_text(errors='replace')):
                    kind = KINDS.get(kind.strip(), 'text')
                    if found.setdefault(name, kind) != kind:
                        raise ValueError(f'{name} is read as both {found[name]} and {kind}')
    return base, patches, found


def swift(base, patches, found):
    rows = ''.join(f'        "{name}":.{kind},\n' for name, kind in sorted(found.items()))
    return ('// Generated by scripts/renderer_settings.py; don\'t edit. The renderer settings the engine reads:\n'
            f'// DXMT {base[:7]} with {", ".join(patches)}.\n'
            'extension RendererSettings {\n'
            '    static let engine:[String:Kind]=[\n'
            f'{rows}'
            '    ]\n'
            '}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--source', type=Path, default=SOURCE, help='a DXMT checkout with the pinned commit')
    parser.add_argument('--check', action='store_true', help='fail if the Swift file is stale')
    args = parser.parse_args()
    text = swift(*settings(args.source))
    if args.check:
        if OUTPUT.read_text() != text:
            sys.exit(f'{OUTPUT.relative_to(ROOT)} is stale: run python3 scripts/renderer_settings.py')
        return
    OUTPUT.write_text(text)
    print(f'{OUTPUT.relative_to(ROOT)}: {text.count(":.")} settings')


if __name__ == '__main__':
    main()
